'use client';

import { Badge, Button, Card, Field, SeverityBadge, Spinner } from '@tracevault/design-system';
import Link from 'next/link';
import { useSearchParams } from 'next/navigation';
import { FormEvent, Suspense, useEffect, useRef, useState } from 'react';
import { PageHead } from '@/components/AppShell';
import { ErrorNotice, Time } from '@/components/bits';
import { api } from '@/lib/api';
import { useApi } from '@/lib/session';

interface Summary {
  provider: string;
  window: { from: string; to: string; label: string };
  headline: string;
  statements: {
    text: string;
    kind: 'fact' | 'inference' | 'gap' | 'advice';
    event_ids: string[];
  }[];
  evidence: {
    id: string;
    label: string;
    device_name: string;
    occurred_at: string;
    severity: 'info' | 'low' | 'medium' | 'high' | 'critical';
  }[];
  completeness: string;
}

const KIND_LABEL = {
  fact: 'Recorded',
  inference: 'Inference',
  gap: 'Missing evidence',
  advice: 'Suggested step',
};
const EXAMPLES = [
  'What happened on my laptop yesterday afternoon?',
  'Were there any unusual security events this week?',
  'Which security settings changed today?',
  'What steps should I take to secure my email?',
];

function Investigate() {
  const params = useSearchParams();
  const devices = useApi<{ items: { id: string; name: string }[] }>('/v1/devices');
  const [question, setQuestion] = useState(
    params.get('alert')
      ? 'Why did I receive this alert, and what happened before and after it?'
      : '',
  );
  const [device, setDevice] = useState('');
  const [result, setResult] = useState<Summary | null>(null);
  const [error, setError] = useState<unknown>(null);
  const [busy, setBusy] = useState(false);
  const auto = useRef(false);

  async function ask(q: string) {
    setBusy(true);
    setError(null);
    try {
      setResult(
        await api<Summary>('/v1/summaries', {
          method: 'POST',
          body: {
            question: q,
            device_id: device || undefined,
            alert_id: params.get('alert') ?? undefined,
          },
        }),
      );
    } catch (e) {
      setError(e);
    } finally {
      setBusy(false);
    }
  }
  useEffect(() => {
    if (params.get('alert') && !auto.current) {
      auto.current = true;
      ask(question);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  function submit(e: FormEvent) {
    e.preventDefault();
    if (question.trim().length >= 3) ask(question.trim());
  }

  return (
    <>
      <PageHead
        title="Investigate"
        description="Ask about your recorded activity. Answers are built only from your own records and link to the events they rely on."
      />
      <div className="stack">
        <Card>
          <form onSubmit={submit}>
            <Field label="Your question" htmlFor="question">
              <input
                className="tv-input"
                id="question"
                value={question}
                onChange={(e) => setQuestion(e.target.value)}
                maxLength={500}
                placeholder={EXAMPLES[0]}
              />
            </Field>
            <div className="tv-row" style={{ alignItems: 'flex-end' }}>
              <Field label="Device" htmlFor="device">
                <select
                  className="tv-select"
                  id="device"
                  value={device}
                  onChange={(e) => setDevice(e.target.value)}
                >
                  <option value="">All my devices</option>
                  {devices.data?.items.map((d) => (
                    <option key={d.id} value={d.id}>
                      {d.name}
                    </option>
                  ))}
                </select>
              </Field>
              <Button variant="primary" type="submit" disabled={busy} style={{ marginBottom: 14 }}>
                Ask
              </Button>
            </div>
          </form>
          <div className="tv-row">
            {EXAMPLES.map((q) => (
              <Button key={q} size="sm" variant="ghost" onClick={() => (setQuestion(q), ask(q))}>
                {q}
              </Button>
            ))}
          </div>
        </Card>
        {busy && <Spinner label="Reviewing your records" />}
        <ErrorNotice error={error} />
        {result && (
          <Card title={result.headline}>
            <p className="tv-small tv-muted">
              Period: {result.window.label} (<Time iso={result.window.from} /> –{' '}
              <Time iso={result.window.to} />
              ). Generated by{' '}
              {result.provider === 'deterministic-v1'
                ? 'TraceVault’s rule-based summarizer (no data sent to any AI provider)'
                : result.provider}
              .
            </p>
            {result.statements.map((s, i) => (
              <div className="statement" data-kind={s.kind} key={i}>
                <Badge
                  tone={
                    s.kind === 'inference'
                      ? 'medium'
                      : s.kind === 'advice'
                        ? 'ok'
                        : s.kind === 'fact'
                          ? 'info'
                          : undefined
                  }
                >
                  {KIND_LABEL[s.kind]}
                </Badge>
                <p style={{ margin: '4px 0' }}>{s.text}</p>
                {s.event_ids.length > 0 && (
                  <div className="tv-small">
                    Evidence:{' '}
                    {s.event_ids.slice(0, 6).map((id, j) => (
                      <span key={id}>
                        {j > 0 && ', '}
                        <Link href={`/timeline?event=${id}`} className="tv-mono">
                          {id.slice(0, 8)}
                        </Link>
                      </span>
                    ))}
                    {s.event_ids.length > 6 && ` +${s.event_ids.length - 6} more`}
                  </div>
                )}
              </div>
            ))}
            {result.evidence.length > 0 && (
              <>
                <h3>Supporting events</h3>
                <ul>
                  {result.evidence.slice(0, 20).map((e) => (
                    <li key={e.id}>
                      <SeverityBadge severity={e.severity} />{' '}
                      <Link href={`/timeline?event=${e.id}`}>{e.label}</Link> on {e.device_name},{' '}
                      <Time iso={e.occurred_at} />
                    </li>
                  ))}
                </ul>
              </>
            )}
          </Card>
        )}
      </div>
    </>
  );
}

export default function InvestigatePage() {
  return (
    <Suspense>
      <Investigate />
    </Suspense>
  );
}
